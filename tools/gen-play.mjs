// Writes the play scripts in tests/native/ that drive the real UI through
// whole sheets: the rules (js/*.js) play the sheet ahead of time — the human
// draws the first open edge (the Home key, then Enter) and the seeded AI
// replies as it will in the game — so each human move waits exactly as long
// as the replies that follow it take (450 ms each plus their animation).
//   node tools/gen-play.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const Rules = require('../js/rules.js');
const Session = require('../js/session.js');
const Content = require('../js/content.js');

/** Steps that play `cfg` (with an optional lesson fixture) to its end by Home + Enter. */
function playSteps(cfg, lesson = null, until = 'Total') {
  const s = Session.create(cfg, cfg.kind);
  if (lesson) Content.applyLessonFixture(s.state, lesson, Rules);
  const out = [];
  let count = 0;
  while (!s.state.over) {
    while (!s.state.over && !Session.isHumanTurn(s)) Session.aiStep(s);
    if (s.state.over) break;
    const e = Rules.legalActions(s.state)[0];
    const res = Session.apply(s, { type: 'draw', dir: e.dir, r: e.r, c: e.c, player: s.state.current });
    if (lesson) {
      const g = lesson.goal;
      count += res.events.filter((ev) => (g.event === 'draw-safe' ? ev.type === 'draw' && ev.gives === false : ev.type === g.event)).length;
    }
    let ai = 0;
    while (!s.state.over && !Session.isHumanTurn(s)) { Session.aiStep(s); ai++; }
    out.push('key Home 2', 'frames 3', 'key Enter 2', `frames ${12 + ai * 34}`);
    if (lesson && count >= lesson.goal.count) break;
  }
  out.push(`until 900 ${until}`, 'frames 10');
  return { steps: out, state: s.state };
}

/** `n` Tab presses (focus moves through the title's cards and links). */
const tabs = (n) => Array.from({ length: n }, () => ['key Tab 2', 'frames 3']).flat();
const header = (lines) => lines.map((l) => `# ${l}`).join('\n') + '\n';
function write(name, text) {
  writeFileSync(join(root, 'tests', 'native', name), text);
  console.log(`wrote tests/native/${name}`);
}

// 1. Journey stage 1 from the title's Play card, played to Results.
{
  const cfg = Content.JOURNEY[0];
  const { steps, state } = playSteps(cfg);
  const out = Rules.outcome(state);
  const headline = out.draw ? 'A tie!' : out.winner === 0 ? 'Victory!' : 'Defeat';
  write('journey-stage.play', header([
    'Journey stage 1 (First Lines, 2×3 against Pip) from the title: the Play card',
    'by Enter, every human line by the keyboard (Home focuses the first open edge,',
    `Enter draws it), Pip's replies by the seeded AI, to Results (${headline} ${state.scores.join('–')}),`,
    'then back to the title by the Title button. Generated by tools/gen-play.mjs.',
  ]) + [
    'until 300 Daily Sheet', 'frames 30', 'save title', 'key Enter 2', 'until 200 Your turn', 'frames 60', 'save sheet',
    ...steps.slice(0, 8), 'save drawing', ...steps.slice(8),
    `expect ${headline}`, 'expect Score breakdown', 'frames 150', 'save results',
    'click Title', 'until 120 Daily Sheet', 'expect Journey', 'frames 5',
  ].join('\n') + '\n');
}

